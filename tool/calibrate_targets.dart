// Offline calibration of random-target difficulty tiers.
//
// For each candidate target, scores a fixed sample of hands with the difficulty
// model and records how often the target is makeable (coverage) and the median
// score of the hands that can make it. Targets are then split into tiers by
// quantiles of median − ln(coverage), and lib/engine/target_tiers.dart is generated.
//
// Usage: dart run tool/calibrate_targets.dart <cards> <all|any> <out.json>
//        dart run tool/calibrate_targets.dart --emit <json files...>
import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:two_dozen/engine/frac.dart';
import 'package:two_dozen/engine/generator.dart';
import 'package:two_dozen/engine/solver.dart';

List<Frac> candidates() {
  final rng = Random(7);
  final out = <Frac>{for (var i = 1; i <= 100; ++i) Frac(i)};
  while (out.length < 330) {
    out.add(Frac(exp(log(101) + rng.nextDouble() * (log(9999) - log(101))).round()));
  }
  while (out.length < 480) {
    final q = 2 + rng.nextInt(11);
    final f = Frac(1 + rng.nextInt(30 * q), q);
    if (!f.isInteger) out.add(f);
  }
  return out.toList();
}

List<List<int>> hands(int cards) {
  if (cards == 4) {
    return [
      for (var a = 1; a <= maxCard; ++a)
        for (var b = a; b <= maxCard; ++b)
          for (var c = b; c <= maxCard; ++c)
            for (var d = c; d <= maxCard; ++d) [a, b, c, d]
    ];
  }
  final rng = Random(11);
  return List.generate(cards <= 6 ? 60 : 40, (_) => dealHand(cards, rng));
}

void calibrate(int cards, bool useAll, String outPath) {
  final hs = hands(cards);
  final rows = [];
  final sw = Stopwatch()..start();
  for (final t in candidates()) {
    final solver = makeSolver(t, cards, useAll);
    final scores = <double>[];
    var eligible = 0;
    for (final h in hs) {
      if (!useAll && t.isInteger && h.contains(t.n)) continue;
      ++eligible;
      final r = solver.analyze(h);
      if (r != null) scores.add(r.score);
    }
    scores.sort();
    rows.add({
      'target': '$t',
      'coverage': scores.length / max(eligible, 1),
      'solvable': scores.length,
      'median': scores.isEmpty ? null : scores[scores.length ~/ 2],
    });
  }
  File(outPath).writeAsStringSync(jsonEncode({'cards': cards, 'useAll': useAll, 'rows': rows}));
  stderr.writeln('$cards/${useAll ? 'all' : 'any'} done in ${sw.elapsed}');
}

/// Quantile cut points of the median score splitting targets into the four tiers.
const tierCuts = [0.25, 0.5, 0.8];

void emit(List<String> paths) {
  final buf = StringBuffer()
    ..writeln('// GENERATED by tool/calibrate_targets.dart — do not edit by hand.')
    ..writeln('//')
    ..writeln('// Candidate targets for each random-target tier (easy, medium, hard, expert),')
    ..writeln('// keyed by "<cards>/<all|any>". Targets are ranked by the median difficulty')
    ..writeln('// score of the sampled hands that can make them, plus a rarity penalty of')
    ..writeln('// −ln(coverage): a target few hands can make is harder to find a route to.')
    ..writeln('const Map<String, List<List<String>>> targetTiers = {');
  for (final p in paths) {
    final data = jsonDecode(File(p).readAsStringSync());
    final cards = data['cards'] as int;
    final useAll = data['useAll'] as bool;
    // Need enough solvable hands that a random batch of deals finds some quickly.
    final minCoverage = cards == 4 ? 10 / 1820 : 0.1;
    double difficulty(dynamic r) => (r['median'] as num) - log(r['coverage'] as num);
    final rows = (data['rows'] as List)
        .where((r) => r['median'] != null && (r['coverage'] as num) >= minCoverage && (r['solvable'] as int) >= 3)
        .toList()
      ..sort((a, b) => difficulty(a).compareTo(difficulty(b)));
    final tiers = List.generate(4, (_) => <String>[]);
    for (var i = 0; i < rows.length; ++i) {
      final q = i / rows.length;
      final tier = tierCuts.where((c) => q >= c).length;
      tiers[tier].add(rows[i]['target'] as String);
    }
    buf.writeln("  '$cards/${useAll ? 'all' : 'any'}': [");
    for (final t in tiers) {
      buf.writeln('    [${t.map((s) => "'$s'").join(', ')}],');
    }
    buf.writeln('  ],');
    stderr.writeln('$cards/${useAll ? 'all' : 'any'}: ${rows.length} targets; '
        'tiers ${tiers.map((t) => t.length).join('/')}; '
        'samples ${tiers.map((t) => t.take(8).join(' ')).join(' | ')}');
  }
  buf.writeln('};');
  File('lib/engine/target_tiers.dart').writeAsStringSync(buf.toString());
}

void main(List<String> args) {
  if (args.first == '--emit') {
    emit(args.sublist(1));
  } else {
    calibrate(int.parse(args[0]), args[1] == 'all', args[2]);
  }
}
